import { copyFile, mkdir, readdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { ZONES } from '../src/games/safari.ts'
import { wildPool } from '../src/games/roster.ts'
import { HELPERS } from '../src/games/safari-zone.ts'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = resolve(scriptDir, '../..')
const sourceDir = resolve(repositoryRoot, 'pokemon-sprites')
const outputDir = resolve(scriptDir, '../assets/safari/pokemon')
const manifestPath = resolve(scriptDir, '../src/generated/safari-pokemon-sprites.js')

export function spriteFileStem(name) {
  return name.normalize('NFKD').replace(/\p{Diacritic}/gu, '').toLowerCase()
    .replace(/['’]/g, '').replace(/[\s-]+/g, '_').replace(/[^a-z0-9_]/g, '').replace(/_+/g, '_').replace(/^_|_$/g, '')
}

export function safariPokemonNames() {
  const names = new Set(Object.values(ZONES).flatMap(({ types }) => wildPool(types).map(wild => wild.name)))
  for (const helper of Object.values(HELPERS)) names.add(helper.name)
  return [...names].sort((a, b) => a.localeCompare(b))
}

export function sourceFilenames(name) {
  const stem = spriteFileStem(name)
  return [`${stem}-0.png`, `${stem}-1.png`, `${stem}-shiny-0.png`, `${stem}-shiny-1.png`]
}

export function missingSpriteFiles(names, available) {
  return [...new Set(names.flatMap(sourceFilenames))].filter(filename => !available.has(filename))
}

function renderManifest(names) {
  const entries = names.flatMap(name => {
    const stem = spriteFileStem(name)
    return [false, true].map(shiny => {
      const key = shiny ? `Shiny ${name}` : name
      const suffix = shiny ? '-shiny' : ''
      const frames = [0, 1].map(frame => `require('../../assets/safari/pokemon/${stem}${suffix}-${frame}.png')`)
      return `  ${JSON.stringify(key)}: [${frames.join(', ')}]`
    })
  })
  return '// Generated by scripts/build-safari-pokemon-sprites.mjs.\nexport const safariPokemonSprites = {\n' +
    entries.join(',\n') + '\n}\n'
}

export async function buildSafariPokemonSprites() {
  const names = safariPokemonNames()
  const available = new Set(await readdir(sourceDir))
  const missing = missingSpriteFiles(names, available)
  if (missing.length) throw new Error(`Missing supplied Safari Pokémon sprite frames: ${missing.join(', ')}`)

  await mkdir(outputDir, { recursive: true })
  for (const name of names) {
    for (const filename of sourceFilenames(name)) {
      await copyFile(resolve(sourceDir, filename), resolve(outputDir, filename))
    }
  }
  await writeFile(manifestPath, renderManifest(names), 'utf8')
  return names.length
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const count = await buildSafariPokemonSprites()
  console.log(`Generated static sprites for ${count} Safari Pokémon.`)
}
